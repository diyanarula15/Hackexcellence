/**
 * Copy text to the clipboard. Tries the async Clipboard API first, then the older execCommand path
 * (works in more embedded browsers). Resolves true on success, false when the browser refused both,
 * so the UI can tell the traveler to copy the reference by hand instead of failing silently.
 */
export async function copyText(text) {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // fall through to the legacy path
  }
  try {
    const area = document.createElement('textarea');
    area.value = text;
    area.setAttribute('readonly', '');
    area.style.position = 'fixed';
    area.style.opacity = '0';
    document.body.append(area);
    area.select();
    const ok = document.execCommand('copy');
    area.remove();
    return ok;
  } catch {
    return false;
  }
}
